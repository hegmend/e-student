const modal = document.getElementById("newsModal");
const modalTitle = document.getElementById("modalTitle");
const modalBody = document.getElementById("modalBody");

/**
 * Відкриває модальне вікно та заповнює його вмістом
 * @param {string} newsKey - Ключ новини (party, lab, water, etc.)
 */
function openModal(newsKey) {
    const data = newsData[newsKey];
    if (data) {
        // Оновлюємо заголовок і тіло модального вікна
        modalTitle.innerHTML = `<h2>${data.title}</h2>`;
        modalBody.innerHTML = data.body;
        
        // Відображаємо модальне вікно
        modal.style.display = "block";
        document.body.style.overflow = 'hidden'; // Запобігаємо прокрутці фону
    }
}

/**
 * Закриває модальне вікно
 */
function closeModal() {
    modal.style.display = "none";
    document.body.style.overflow = 'auto'; // Дозволяємо прокрутку фону
}

// Закриття вікна при натисканні клавіші ESC або кліку поза вікном
window.onkeydown = function(event) {
    if (event.key === "Escape") {
        closeModal();
    }
};

modal.addEventListener('click', function(event) {
    if (event.target === modal) {
        closeModal();
    }
});